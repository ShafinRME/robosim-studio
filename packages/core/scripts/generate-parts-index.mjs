// Writes packages/core/src/parts/library/index.ts: one import per part file in the folder, sorted
// (ADR 010). Run with `pnpm parts` after adding, renaming or removing a part file.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const here = path.dirname(fileURLToPath(import.meta.url));
const folder = path.resolve(here, "../src/parts/library");

export function partFiles(dir = folder) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.endsWith(".test.ts"))
    .map((f) => f.slice(0, -3))
    .sort();
}

const identifier = (name) => name.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase());

const files = partFiles();
for (const name of files) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`part file "${name}.ts": use lowercase words joined by "-"`);
  }
}
const source = `// Generated by \`pnpm parts\` (packages/core/scripts/generate-parts-index.mjs). Do not edit.
// One import per file in this folder, sorted (ADR 010).
import type { PartDefinition } from "../part";
${files.map((f) => `import ${identifier(f)} from "./${f}";`).join("\n")}

export const LIBRARY: readonly PartDefinition[] = [${files.map(identifier).join(", ")}];
`;
const config = (await prettier.resolveConfig(folder)) ?? {};
const formatted = await prettier.format(source, { ...config, parser: "typescript" });
writeFileSync(path.join(folder, "index.ts"), formatted);
process.stdout.write(`Parts index: ${files.length} parts (${files.join(", ")})\n`);
